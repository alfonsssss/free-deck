// Packs the game rules (engines/ + engine-room.js) into public/rules.js so the browser can run
// games against the computer by itself, without the server. Runs automatically on `npm start`
// and in the CrazyGames build. Never edit public/rules.js by hand.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'public', 'rules.js');
const files = ['engine-room.js', ...fs.readdirSync(path.join(ROOT, 'engines')).filter(f => f.endsWith('.js')).map(f => 'engines/' + f)];

const mods = files.map(f => {
  const id = f.replace(/\.js$/, '');
  const src = fs.readFileSync(path.join(ROOT, f), 'utf8');
  return `${JSON.stringify(id)}: function (module, exports, require) {\n${src}\n}`;
}).join(',\n');

const out = `// GENERATED by scripts/build-rules.js from engines/ and engine-room.js – do not edit.
(function () {
  // what the rules need from Node, done the browser way
  const shims = {
    crypto: { randomInt(max) { const a = new Uint32Array(1); const lim = Math.floor(0x100000000 / max) * max; let x; do { crypto.getRandomValues(a); x = a[0]; } while (x >= lim); return x % max; } },
    db: { countPlay() {} },
  };
  const defs = {
${mods}
  };
  const cache = {};
  function resolve(from, name) {
    if (!name.startsWith('.')) return name;
    const parts = from.split('/').slice(0, -1);
    for (const p of name.split('/')) { if (p === '..') parts.pop(); else if (p !== '.') parts.push(p); }
    const id = parts.join('/');
    return defs[id] || shims[id] ? id : id + '/index';
  }
  function load(id) {
    if (shims[id]) return shims[id];
    if (cache[id]) return cache[id].exports;
    const module = (cache[id] = { exports: {} });
    defs[id](module, module.exports, name => load(resolve(id, name)));
    return module.exports;
  }
  window.KB_RULES = load('engine-room');
})();
`;
fs.writeFileSync(OUT, out);
if (require.main === module) console.log(`✔ ${path.relative(ROOT, OUT)} (${(out.length / 1024).toFixed(0)} kB)`);
